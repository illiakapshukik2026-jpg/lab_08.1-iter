#define _CRT_SECURE_NO_WARNINGS // Дозволяє використовувати застарілі безпечні функції в MSVC без помилок компілятора
#include <iostream>             
#include <cstring>              
#include <cassert>              

using namespace std;            

// Функція для підрахунку кількості пар "SQ" або "QS" ітераційним способом
int Count(const char* str)
{
    if (strlen(str) < 2)        // Перевірка, чи довжина рядка менша за 2 символи
        return 0;               // Якщо менша, пар не може бути, повертаємо 0

    int k = 0;                  // Оголошення та ініціалізація лічильника знайдених пар
    for (int i = 0; str[i + 1] != '\0'; i++) // Цикл для послідовного сканування рядка до передостаннього символу
    {
        // Перевірка наявності пари "SQ" або "QS" на позиціях i та i+1
        if ((str[i] == 'S' && str[i + 1] == 'Q') || (str[i] == 'Q' && str[i + 1] == 'S'))
        {
            k++;                // Збільшення лічильника на 1 при знаходженні цільової пари
        }
    }
    return k;                   // Повернення загальної кількості знайдених пар
}

// Функція для заміни кожної пари "SQ" або "QS" на трійку зірочок "***" ітераційним способом
char* Change(char* str)
{
    size_t len = strlen(str);   // Отримання довжини вхідного рядка
    char* tmp = new char[len * 3 + 1]; // Виділення динамічної пам'яті для тимчасового рядка з запасом
    char* t = tmp;              // Вказівник на поточну позицію в тимчасовому рядку
    tmp[0] = '\0';              // Ініціалізація тимчасового рядка як порожнього

    int i = 0;                  // Ініціалізація індексу для сканування вхідного рядка
    while (str[i] != '\0')      // Цикл виконується, поки не досягнуто кінця вхідного рядка
    {
        // Перевірка, чи поточні два символи утворюють "SQ" або "QS"
        if (str[i + 1] != '\0' &&
            ((str[i] == 'S' && str[i + 1] == 'Q') || (str[i] == 'Q' && str[i + 1] == 'S')))
        {
            strcat(t, "***");   // Додавання трійки зірочок до тимчасового рядка
            t += 3;             // Зміщення вказівника тимчасового рядка на 3 позиції вперед
            i += 2;             // Пропускання 2 символів опрацьованої пари у вхідному рядку
        }
        else
        {
            *t++ = str[i++];    // Копіювання звичайного символу та інкремент вказівників
            *t = '\0';          // Дописування нуль-термінатора для підтримки валідності рядка
        }
    }

    strcpy(str, tmp);           // Копіювання результату назад у початковий рядок-параметр
    return tmp;                 // Повернення вказівника на новий результуючий рядок
}

// Функція для запуску юніт-тестів ітераційної реалізації
void RunUnitTests()
{
    cout << "Running Unit Tests (Iterative)..." << endl;

    // Тест 1: Перевірка підрахунку Count для різних комбінацій
    char test1[50] = "AQSBCSQD";
    assert(Count(test1) == 2); // Має знайти дві пари: "QS" та "SQ"

    // Тест 2: Перевірка підрахунку Count для рядка без пар
    char test2[50] = "HELLO WORLD";
    assert(Count(test2) == 0); // Пар немає, результат 0

    // Тест 3: Перевірка заміни Change
    char test3[50] = "ASQBCQS";
    char* res3 = Change(test3);
    assert(strcmp(test3, "A***BC***") == 0); // Перевірка зміни параметра
    assert(strcmp(res3, "A***BC***") == 0);  // Перевірка результату функції
    delete[] res3;

    cout << "All iterative unit tests passed successfully!\n" << endl;
}

int main()
{
    RunUnitTests();             // Виклик юніт-тестів перед основною програмою

    char str[101];              // Оголошення масиву для введення рядка користувачем
    cout << "Enter string:" << endl; // Виведення запрошення до введення
    cin.getline(str, 100);      // Безпечне зчитування рядка з консолі

    // Виведення кількості знайдених пар
    cout << "String contained " << Count(str) << " pairs of 'SQ' or 'QS'" << endl;

    char* dest = new char[151]; // Виділення пам'яті під результат
    dest = Change(str);         // Виклик функції заміни

    cout << "Modified string (param) : " << str << endl;  
    cout << "Modified string (result): " << dest << endl; 

    delete[] dest;              
    return 0;                  
}
